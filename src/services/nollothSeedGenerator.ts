export function generateNollothJemaatSeed(): Jemaat[] {
  const result: Jemaat[] = [];
  const usedNkkBases: Record<string, number> = {
    JG01011504197801: 1,
    JG01021006197501: 1,
    JG02011809197001: 1,
    JG02020507195501: 1,
    JG01011211198402: 1,
    JG02011811196801: 1,
  };

  let idCounter = 17;

  NOLLOTH_FAMILIES.forEach((fam) => {
    const kk = fam.members.find((m) => m.hubungan === 'Kepala Keluarga') || fam.members[0];
    const nkk = buildNkk(fam.sektor, fam.unit, kk.tanggalLahir, kk.jk, usedNkkBases);

    fam.members.forEach((m) => {
      const currentIdx = idCounter++;
      const umur = calcAgeAtRef(m.tanggalLahir);
      const isMarried = Boolean(m.isMarried);
      const wadah: WadahKategorial = determineWadahKategorial(umur, m.jk, isMarried);
      const tglBaptis = addYearsDate(m.tanggalLahir, 0, undefined, undefined)
        ? (() => {
            const d = new Date(m.tanggalLahir);
            d.setMonth(d.getMonth() + 3);
            if (d.getFullYear() > REFERENCE_YEAR) return '';
            return d.toISOString().slice(0, 10);
          })()
        : '';
      const tglSidi = umur >= 17 ? addYearsDate(m.tanggalLahir, 17, '10', '29') : '';

      result.push({
        id: `jem-${currentIdx}`,
        nik: buildNik(fam.sektor, fam.unit, m.tanggalLahir, m.jk, currentIdx),
        nkk,
        nama: m.nama,
        jenisKelamin: m.jk,
        tempatLahir: m.tempatLahir,
        tanggalLahir: m.tanggalLahir,
        umur,
        golonganDarah: m.golDarah,
        pendidikan: m.pendidikan,
        pekerjaan: m.pekerjaan,
        pekerjaanLainnya: m.pekerjaanLainnya || '',
        disabilitas: 'Tidak',
        statusSosial: m.statusSosial || 'Umum',
        hubunganKeluarga: m.hubungan,
        statusKeanggotaan: m.statusKeanggotaan || 'Jemaat Tetap',
        sektor: fam.sektor,
        unit: fam.unit,
        tglBaptis,
        tglSidi,
        tglNikah: m.tglNikah || '',
        jabatanStruktural: m.jabatanStruktural || 'None',
        jabatanPelayan: m.jabatanPelayan || 'None',
        wadahKategorial: wadah,
        pengurusIntiWadah: m.pengurusWadah || 'None',
        noHp: m.noHp || '',
        email: m.email || '',
        alamat: fam.alamat,
        keterangan: m.keterangan || 'Jemaat GPI Getsemani Sorong (Marga Negeri Nolloth)',
      });
    });
  });

  return result;
}
