const REFERENCE_YEAR = 2026;
const REFERENCE_MONTH = 11; // November
const REFERENCE_DAY = 13;

function calcAgeAtRef(birthDate: string): number {
  const [y, m, d] = birthDate.split('-').map(Number);
  if (!y || !m || !d) return 30;
  let age = REFERENCE_YEAR - y;
  if (REFERENCE_MONTH < m || (REFERENCE_MONTH === m && REFERENCE_DAY < d)) {
    age--;
  }
  return Math.max(0, age);
}

function addYearsDate(birthDate: string, yearsToAdd: number, monthOverride?: string, dayOverride?: string): string {
  const [y, m, d] = birthDate.split('-');
  const targetYear = Number(y) + yearsToAdd;
  if (targetYear > REFERENCE_YEAR) return '';
  return `${targetYear}-${monthOverride || m}-${dayOverride || d}`;
}

function buildNik(
  sektor: SektorName,
  unit: UnitName,
  birthDate: string,
  jk: JenisKelamin,
  seq: number
): string {
  const [y, m, d] = birthDate.split('-');
  const dayNum = Number(d) + (jk === 'Perempuan' ? 40 : 0);
  const dd = String(dayNum).padStart(2, '0');
  const yy = y.slice(2, 4);
  const unitIdx = unit === 'Rehobot' ? '01' : unit === 'Silo' ? '02' : unit === 'Pniel' ? '03' : '04';
  const prefix = sektor === 'Filadelfia' ? `9271${unitIdx}` : `9271${unitIdx}`;
  return `${prefix}${dd}${m}${yy}${String(seq).padStart(4, '0')}`;
}

function buildNkk(
  sektor: SektorName,
  unit: UnitName,
  kkBirthDate: string,
  kkJk: JenisKelamin,
  usedNkkBases: Record<string, number>
): string {
  const sCode = SEKTOR_CODES[sektor];
  const uCode = UNIT_CODES[unit];
  const [y, m, d] = kkBirthDate.split('-');
  const jkCode = kkJk === 'Laki-laki' ? '01' : '02';
  const base16 = `JG${sCode}${uCode}${d}${m}${y}${jkCode}`;
  const nextCount = (usedNkkBases[base16] || 0) + 1;
  usedNkkBases[base16] = nextCount;
  return `${base16}${String(nextCount).padStart(2, '0')}`;
}

